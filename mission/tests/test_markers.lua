T.test("parses marker commands", function()
  T.fresh()
  local p = RH.markers.parse
  T.eq(p("-illumination").cmd, "illumination")
  T.eq(p("  -WPZONE ").cmd, "wpzone")
  T.eq(p("-farp?").cmd, "farp?")
  T.eq(p("-extract").cmd, "extract")
  local s = p("-smoke,green")
  T.eq(s.cmd, "smoke")
  T.eq(s.color, "green")
  T.eq(p("-smoke,purple").cmd, "invalid")
  T.eq(p("SA-15 here"), nil)
  T.eq(p(nil), nil)
end)

T.test("smoke requires the player within 15 km", function()
  local w = T.fresh()
  RH.markers.handle({ text = "-smoke,red", pos = { x = 0, y = 0, z = 0 }, initiatorName = "u1", initiatorPos = { x = 20000, y = 0, z = 0 } })
  T.eq(#w.smokes, 0)
  T.ok(w.anyMessage("within 15 km"))
  RH.markers.handle({ text = "-smoke,red", pos = { x = 0, y = 0, z = 0 }, initiatorName = "u1", initiatorPos = { x = 5000, y = 0, z = 0 } })
  T.eq(#w.smokes, 1)
  T.eq(w.smokes[1].color, 1)
end)

T.test("illumination drops several bursts over time", function()
  local w = T.fresh()
  RH.markers.handle({ text = "-illumination", pos = { x = 0, y = 0, z = 0 } })
  T.eq(#w.illuminations, 1)
  w.advance(RH.config.markers.illuminationSpacing * 10)
  T.eq(#w.illuminations, RH.config.markers.illuminationBursts)
end)

T.test("wpzone is found within 1 NM and removed with the mark", function()
  T.fresh()
  RH.markers.handle({ text = "-wpzone", pos = { x = 1000, y = 0, z = 1000 }, markId = 7 })
  local wp = RH.markers.wpzoneFor({ x = 1500, y = 1500 })
  T.ok(wp ~= nil, "wpzone should be found")
  T.eq(wp.x, 1000)
  T.eq(RH.markers.wpzoneFor({ x = 9000, y = 9000 }), nil)
  RH.markers.onRemoved({ markId = 7 })
  T.eq(RH.markers.wpzoneFor({ x = 1500, y = 1500 }), nil)
end)

T.test("-farp? shows circles then clears them, and is rate limited", function()
  local w = T.fresh()
  RH.logistics.register("RH_FARP_ALPHA", { x = 0, y = 0 })
  RH.markers.handle({ text = "-farp?", pos = { x = 0, y = 0, z = 0 } })
  T.ok(w.drawings["farp?-RH_FARP_ALPHA"] ~= nil, "circle drawn")
  T.eq(w.drawings["farp?-RH_FARP_ALPHA"].radius, RH.config.farp.minSeparation)
  RH.markers.handle({ text = "-farp?", pos = { x = 0, y = 0, z = 0 } })
  T.ok(w.anyMessage("already displayed"))
  w.advance(61)
  T.eq(w.drawings["farp?-RH_FARP_ALPHA"], nil)
end)
